export async function loadSimklinikSnapshot(
  role: SimklinikRole
): Promise<{ data: SimklinikSnapshot; connected: boolean }> {
  const sb = getBrowserSupabase();
  if (sb) {
    try {
      const { data, error } = await sb.rpc('tw_simklinik_dashboard_snapshot', {
        p_role: role,
      });
      if (!error && data) {
        return { data: data as SimklinikSnapshot, connected: true };
      }
    } catch {
      // Fallback for offline/sandbox environment
    }
  }

  // Apply identical UU PDP RBAC masking on fallback data when role is KASIR_KEUANGAN
  const cloned: SimklinikSnapshot = {
    ...FALLBACK_SIMKLINIK_DATA,
    active_role: role,
    soap_sessions:
      role === 'KASIR_KEUANGAN' ? [] : FALLBACK_SIMKLINIK_DATA.soap_sessions,
  };
  return { data: cloned, connected: false };
}

export function formatRupiah(amount: number): string {
  return new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    maximumFractionDigits: 0,
  }).format(amount);
}
